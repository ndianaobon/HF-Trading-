import { html, $, on, mount, param } from "../core/dom.js";
import { icon } from "../core/icons.js";
import { api } from "../core/api.js";
import { invalidate } from "../core/store.js";
import { pageHeader, statusBadge, smallDemo, notice, emptyState, skeleton, toast, openModal } from "../core/ui.js";
import { countryName } from "../core/countries.js";
import { formatDate, titleCase } from "../core/format.js";
import { adminPage, adminTable } from "../components/admin-kit.js";

const { user: admin, view } = await adminPage();
mount(view, html`${pageHeader({ title: "KYC review", description: "Review identity documents. Viewing documents is recorded in the audit log." })}<div data-list></div>`);

adminTable($("[data-list]", view), {
  endpoint: "/api/admin/kyc",
  filters: [
    { name: "status", type: "select", default: "PENDING", options: [["PENDING", "Pending"], ["APPROVED", "Approved"], ["REJECTED", "Rejected"], ["", "All"]] },
    { name: "q", type: "search", placeholder: "Search name or email", cls: "md:w-72" },
  ],
  onRowClick: (r) => openApplication(r.id),
  empty: emptyState({ title: "Nothing in this queue" }),
  columns: [
    { key: "n", header: "Applicant", cell: (r) => html`<div><p class="flex items-center gap-2 font-semibold text-white">${r.fullName} ${r.user.isDemo ? smallDemo() : ""}</p><p class="text-xs text-dim">${r.user.email}</p></div>` },
    { key: "c", header: "Country", cell: (r) => countryName(r.country) },
    { key: "id", header: "ID type", hideOnMobile: true, cell: (r) => titleCase(r.idType) },
    { key: "docs", header: "Docs", align: "right", cell: (r) => String(r._count.documents) },
    { key: "sub", header: "Submitted", cell: (r) => html`<span class="text-xs text-muted">${formatDate(r.submittedAt)}</span>` },
    { key: "s", header: "Status", cell: (r) => statusBadge(r.status) },
  ],
});

async function openApplication(id) {
  const m = openModal({ title: "KYC application", size: "lg", body: skeleton("h-64 w-full") });
  let d;
  try {
    d = await api(`/api/admin/kyc/${id}`);
  } catch (err) {
    return m.setBody(notice("down", { body: err.message }));
  }
  const canReview = d.status === "PENDING" && admin.can("kyc.review");
  const rows = [
    ["Full name", d.fullName],
    ["Date of birth", formatDate(d.dateOfBirth, "date")],
    ["Country", countryName(d.country)],
    ["Address", `${d.addressLine}, ${d.city} ${d.postalCode}`],
    ["ID type", titleCase(d.idType)],
    ["ID number", d.idNumberMasked ?? "—"],
    ["Status", statusBadge(d.status)],
    ["Reviewed", d.reviewedAt ? `${formatDate(d.reviewedAt)} by ${d.reviewedBy?.email ?? "—"}` : "—"],
  ];
  m.setBody(html`<div class="space-y-5">
    <p class="-mt-2 text-sm text-muted">${d.user.email}</p>
    ${d.user.isDemo ? notice("warn", { body: "Demo applicant — documents are placeholder files generated by the seed script." }) : ""}
    <dl class="grid gap-3 text-sm sm:grid-cols-2">${rows.map(([k, v]) => html`<div><dt class="text-xs text-dim">${k}</dt><dd class="text-white">${v}</dd></div>`)}</dl>
    ${d.rejectionReason ? notice("down", { body: `Rejection reason: ${d.rejectionReason}` }) : ""}
    <div><p class="mb-2 text-xs font-bold tracking-wider text-dim uppercase">Documents</p>
      <div class="grid gap-2 sm:grid-cols-2">${d.documents.map(
        (doc) => html`<a href="/api/files?key=${encodeURIComponent(doc.storageKey)}" target="_blank" rel="noopener" class="flex items-center justify-between rounded-xl border border-line bg-base-2 p-3 hover:border-accent/40"><span class="flex items-center gap-2 text-sm">${icon("file-text", "h-4 w-4 text-accent")}<span><span class="block font-semibold text-white">${titleCase(doc.type)}</span><span class="block text-xs text-dim">${doc.fileName} · ${(doc.size / 1024).toFixed(0)} KB</span></span></span>${icon("external-link", "h-4 w-4 text-dim")}</a>`,
      )}</div>
    </div>
    <a href="/admin/users/${d.user.id}" class="inline-flex text-sm font-semibold text-accent">Open user profile →</a>
    ${canReview ? html`<div class="field"><label class="label" for="kyc-r">Rejection reason (shown to the user)</label><textarea id="kyc-r" rows="2" class="textarea" maxlength="500"></textarea></div>` : ""}
    <div data-err></div>
  </div>`);
  if (d.status === "PENDING") m.setFooter(canReview ? html`<button type="button" class="btn btn-danger" data-decide="REJECTED">Reject</button><button type="button" class="btn btn-primary" data-decide="APPROVED">Approve</button>` : html`<p class="text-xs text-dim">You have read-only access.</p>`);
  on(m.el, "click", "[data-decide]", async (_e, b) => {
    const decision = b.dataset.decide;
    const reason = $("#kyc-r", m.el)?.value.trim() ?? "";
    const fail = (msg) => mount($("[data-err]", m.el), notice("down", { body: msg }));
    if (decision === "REJECTED" && reason.length < 3) return fail("Enter a rejection reason the user will see.");
    b.disabled = true;
    try {
      await api(`/api/admin/kyc/${id}`, { body: { decision, reason: reason || undefined } });
      toast.success(decision === "APPROVED" ? "Application approved" : "Application rejected");
      m.close();
      ["/api/admin/kyc", "/api/admin/overview"].forEach(invalidate);
    } catch (err) {
      b.disabled = false;
      fail(err.message);
    }
  });
}

if (param("open")) openApplication(param("open"));
